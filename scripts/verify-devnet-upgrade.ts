/** Read-only bytecode verification plus a transaction simulation (no funds move). */
import dotenv from "dotenv";
import { Connection, PublicKey, TransactionMessage, VersionedTransaction } from "@solana/web3.js";
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { makeProvider, program as mkProgram, pdas, PROGRAM_ID } from "@bisik/sdk";
import { Keypair } from "@solana/web3.js";
dotenv.config({ path: new URL("../.env", import.meta.url).pathname, quiet: true });
const connection = new Connection(process.env.SOLANA_RPC_URL!, "confirmed");
const genesis = await connection.getGenesisHash();
if (genesis !== await new Connection("https://api.devnet.solana.com").getGenesisHash()) throw Error("Not devnet");
const info = await connection.getAccountInfo(PROGRAM_ID);
if (!info?.executable || !info.owner.equals(new PublicKey("BPFLoaderUpgradeab1e11111111111111111111111"))) throw Error("Unexpected program owner");
const programDataKey = new PublicKey(info.data.subarray(4, 36));
const programData = await connection.getAccountInfo(programDataKey);
if (!programData || programData.data.readUInt32LE(0) !== 3) throw Error("Unexpected programdata");
const binary = readFileSync(new URL("../contracts/target/deploy/bisik.so", import.meta.url));
const live = programData.data.subarray(45);
if (!live.subarray(0, binary.length).equals(binary) || live.subarray(binary.length).some(b => b !== 0)) throw Error("Deployed binary does not match tested build");
const slot = Number(programData.data.readBigUInt64LE(4));
const authority = new PublicKey(programData.data.subarray(13, 45));
const program: any = mkProgram(makeProvider(connection, Keypair.generate()));
const p = pdas(PROGRAM_ID);
const config = await program.account.config.fetch(p.config());
const market = p.market(0);
const ix = await program.methods.payTeamShare(0).accounts({ operator: config.operator, config: p.config(), market, option: p.option(market, 0), teamToken: config.treasury, escrow: p.escrow(market), tokenProgram: new PublicKey("TokenkegQfeZyiNwAJbNbGKPFXCWuBvf9Ss623VQ5DA") }).instruction();
const block = await connection.getLatestBlockhash();
const tx = new VersionedTransaction(new TransactionMessage({ payerKey: config.operator, recentBlockhash: block.blockhash, instructions: [ix] }).compileToV0Message());
const result = await connection.simulateTransaction(tx, { sigVerify: false });
if (JSON.stringify(result.value.err) !== JSON.stringify({ InstructionError: [0, { Custom: 6024 }] })) throw Error("Expected TeamShareRemoved; got " + JSON.stringify(result.value));
const report = { programId: PROGRAM_ID.toBase58(), programData: programDataKey.toBase58(), slot, authority: authority.toBase58(), binarySha256: createHash("sha256").update(binary).digest("hex"), liveBinaryMatches: true, legacyTeamPaymentSimulation: result.value.err, legacyConfigTeamBps: config.teamBps, logs: result.value.logs };
writeFileSync(new URL("../tmp/devnet-upgrade-verification.json", import.meta.url), JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
