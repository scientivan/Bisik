// B2: generate the Semaphore v4 (depth 20) verification key as Rust constants for groth16-solana.
// Usage: node scripts/gen-vk.mjs   (run `pnpm --filter @bisik/zk test` once first so the zkey is cached)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { tmpdir } from "node:os";
import { join } from "node:path";

const base = join(tmpdir(), "snark-artifacts", "semaphore");
if (!existsSync(base)) throw new Error(`no cached artifacts in ${base}; run the zk tests first`);
const version = readdirSync(base).sort().pop();
const zkey = join(base, version, "semaphore-20.zkey");
const vkJson = join(tmpdir(), "bisik-semaphore-20-vk.json");
execFileSync("snarkjs", ["zkey", "export", "verificationkey", zkey, vkJson], { stdio: "ignore" });
const vk = JSON.parse(readFileSync(vkJson, "utf8"));
const zkeyHash = createHash("sha256").update(readFileSync(zkey)).digest("hex");

const be32 = (x) => Array.from(Buffer.from(BigInt(x).toString(16).padStart(64, "0"), "hex"));
const g1 = (p) => [...be32(p[0]), ...be32(p[1])];
const g2 = (p) => [...be32(p[0][1]), ...be32(p[0][0]), ...be32(p[1][1]), ...be32(p[1][0])];
const arr = (a) => `[${a.join(", ")}]`;

const out = `// @generated by scripts/gen-vk.mjs — do not edit.
// Semaphore v4 verification key, Merkle depth 20 (snark-artifacts semaphore ${version}).
// sha256(semaphore-20.zkey) = ${zkeyHash}
use groth16_solana::groth16::Groth16Verifyingkey;

pub const VK_IC: [[u8; 64]; ${vk.IC.length}] = [
${vk.IC.map((p) => "    " + arr(g1(p)) + ",").join("\n")}
];

pub const VERIFYING_KEY: Groth16Verifyingkey = Groth16Verifyingkey {
    nr_pubinputs: ${vk.nPublic},
    vk_alpha_g1: ${arr(g1(vk.vk_alpha_1))},
    vk_beta_g2: ${arr(g2(vk.vk_beta_2))},
    vk_gamme_g2: ${arr(g2(vk.vk_gamma_2))},
    vk_delta_g2: ${arr(g2(vk.vk_delta_2))},
    vk_ic: &VK_IC,
};
`;
const target = new URL("../contracts/programs/bisik/src/vk.rs", import.meta.url);
writeFileSync(target, out);
console.log(`wrote ${target.pathname} (semaphore ${version}, nPublic ${vk.nPublic}, zkey sha256 ${zkeyHash.slice(0, 16)}…)`);
